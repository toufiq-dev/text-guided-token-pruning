#!/usr/bin/env python3
"""06_generate_report.py — build the final experiment report (markdown).

Aggregates results from --results-dir and --ablations-json into a single
``docs/experiments_report.md`` with:
  * accuracy/efficiency tables per benchmark and per ratio
  * ablation summary table
  * D7 random-vs-smart verdict

Usage:
    python scripts/06_generate_report.py --results-dir outputs/results \
        --ablations-json outputs/ablations/ablations.json --report docs/experiments_report.md
"""

from __future__ import annotations

import argparse
import json
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "src"))

from tgtp.evaluation.diagnostics import random_vs_smart_delta
from tgtp.utils.logging import get_logger

logger = get_logger("tgtp.report")


def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(description="Generate the final experiment report.")
    p.add_argument("--results-dir", default="outputs/results")
    p.add_argument("--ablations-json", default="outputs/ablations/ablations.json")
    p.add_argument("--report", default="docs/experiments_report.md")
    p.add_argument("--accuracy-budget", type=float, default=2.0)
    return p.parse_args()


def load_json(path: str) -> list:
    if os.path.exists(path):
        with open(path, "r", encoding="utf-8") as fh:
            return json.load(fh)
    return []


def main() -> None:
    args = parse_args()
    rows = load_json(args.results_dir) if args.results_dir.endswith(".json") else _load_dir(args.results_dir)
    ablations = load_json(args.ablations_json)
    if isinstance(ablations, dict):
        ablations = [{"name": k, **v} for k, v in ablations.items()]

    lines = ["# Experiment report", "", "_Generated by scripts/06_generate_report.py_", ""]

    # ---- accuracy/efficiency tables -----------------------------------------
    lines.append("## Accuracy vs efficiency", "")
    lines.append("| benchmark | method | ratio | acc | flops_reduction | latency_ms |")
    lines.append("|---|---|---|---|---|---|")
    for r in sorted(rows, key=lambda x: (x.get("benchmark", ""), x.get("scoring", ""), x.get("prune_ratio", 0))):
        lines.append(
            f"| {r.get('benchmark')} | {r.get('scoring')} | {r.get('prune_ratio')} | "
            f"{r.get('accuracy', float('nan')):.4f} | {r.get('flops_reduction_ratio', 0) * 100:.1f}% | "
            f"{r.get('latency_mean_ms', 0):.1f} |"
        )
    lines.append("")

    # ---- ablations ----------------------------------------------------------
    if ablations:
        lines.append("## Ablations", "")
        lines.append("| ablation | accuracy | note |")
        lines.append("|---|---|---|")
        for a in ablations:
            lines.append(f"| {a.get('name')} | {a.get('accuracy', float('nan')):.4f} | {a.get('note', '')} |")
        lines.append("")

    # ---- D7 verdict ---------------------------------------------------------
    smart = {float(r["prune_ratio"]): r["accuracy"] for r in rows if r.get("scoring") == "cross_attention"}
    random = {float(r["prune_ratio"]): r["accuracy"] for r in rows if r.get("scoring") == "random"}
    if smart and random:
        d7 = random_vs_smart_delta(smart, random)
        lines.append("## D7 — random vs. text-guided", "")
        for ratio, delta in sorted(d7["deltas"].items(), key=lambda kv: float(kv[0])):
            lines.append(f"- ratio {float(ratio):.2f}: delta {delta:+.4f}")
        lines.append(f"- text-guided wins at {d7['ratios_where_smart_wins']}/{d7['total_ratios']} ratios")
        lines.append("")

    os.makedirs(os.path.dirname(args.report) or ".", exist_ok=True)
    with open(args.report, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    logger.info("Wrote report -> %s", args.report)


def _load_dir(results_dir: str) -> list:
    rows = []
    if os.path.isdir(results_dir):
        for fname in sorted(os.listdir(results_dir)):
            if fname.endswith(".json"):
                with open(os.path.join(results_dir, fname), "r", encoding="utf-8") as fh:
                    rows.append(json.load(fh))
    return rows


if __name__ == "__main__":
    main()
